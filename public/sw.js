// LeetCram Service Worker
// Unique build version injected during build
const CACHE_VERSION = "__SW_VERSION__";
const CACHE_NAME = `leetcram-${CACHE_VERSION.includes("__") ? "dev" : CACHE_VERSION}`;

const PRECACHE_ASSETS = [
  "./",
  "./index.html",
  "./manifest.webmanifest",
  "./logo.png",
  "./favicon.png",
  "./icon-192.png",
  "./icon-512.png",
  "./apple-touch-icon.png",
];

// Install: Pre-cache shell assets and skip waiting immediately
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_ASSETS))
      .then(() => self.skipWaiting())
      .catch((err) => console.warn("[SW] Install pre-cache error:", err))
  );
});

// Activate: Clean up obsolete caches and claim existing clients
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((cacheNames) => {
        return Promise.all(
          cacheNames.map((name) => {
            if (name !== CACHE_NAME && name.startsWith("leetcram-")) {
              console.log("[SW] Removing outdated cache:", name);
              return caches.delete(name);
            }
          })
        );
      })
      .then(() => self.clients.claim())
  );
});

// Message listener for skip waiting or checking version
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
  if (event.data && event.data.type === "CHECK_VERSION") {
    event.ports[0]?.postMessage({ version: CACHE_NAME });
  }
});

// Fetch handler:
// 1. Navigation / HTML -> Network-first (so new index.html with new bundle hashes is retrieved immediately)
// 2. /assets/ -> Cache-first (Vite content-hashed bundles)
// 3. Other static assets -> Stale-while-revalidate
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;

  const url = new URL(event.request.url);

  // Ignore chrome-extension and non-http schemes
  if (!url.protocol.startsWith("http")) return;

  // Never cache or intercept sw.js itself to ensure update checks always reach the network
  if (url.pathname.endsWith("sw.js")) return;

  // Navigation (HTML pages)
  if (event.request.mode === "navigate" || url.pathname.endsWith("/index.html") || url.pathname === "/") {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        })
        .catch(async () => {
          const cached = await caches.match(event.request);
          if (cached) return cached;
          return caches.match("./index.html") || caches.match("./");
        })
    );
    return;
  }

  // Content-hashed assets generated by Vite
  if (url.pathname.includes("/assets/")) {
    event.respondWith(
      caches.match(event.request).then((cachedResponse) => {
        if (cachedResponse) return cachedResponse;
        return fetch(event.request).then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const clone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return networkResponse;
        });
      })
    );
    return;
  }

  // General static assets (icons, images, manifest)
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      const fetchPromise = fetch(event.request)
        .then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const clone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return networkResponse;
        })
        .catch(() => cachedResponse);

      return cachedResponse || fetchPromise;
    })
  );
});
